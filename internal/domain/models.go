// Package domain defines the request, response and graph types.
package domain

// AdaptivePlanRequest is the inbound HTTP request body accepted by the
// POST /api/v1/adaptive-plan endpoint. It encapsulates the student context
// required by the multi-stage reasoning pipeline to produce a personalized
// study plan.
//
// Required fields: FailedTopics (at least one element) and VARKProfile.
// StudentID and CourseID are propagated into the LLM prompt and returned
// verbatim in the response envelope.
type AdaptivePlanRequest struct {
	// StudentID is the platform-level identifier for the learner.
	StudentID string `json:"student_id" example:"student-42"`

	// CourseID identifies the course within which the adaptive plan is scoped.
	CourseID string `json:"course_id" example:"cs101"`

	// FailedTopics is a non-empty list of knowledge-graph node names
	// representing concepts the student has not yet mastered.
	FailedTopics []string `json:"failed_topics" example:"Polymorphism,Recursion"`

	// VARKProfile specifies the student's dominant learning modality.
	// Accepted values: "visual", "auditory", "read_write", "kinesthetic".
	VARKProfile string `json:"vark_profile" example:"visual"`

	// Telemetry carries optional client-side diagnostic metadata.
	// When nil, telemetry is omitted from the serialized payload.
	Telemetry *Telemetry `json:"telemetry,omitempty"`
}

// Telemetry captures optional client-side diagnostics attached to an
// AdaptivePlanRequest. It is intended for downstream analytics pipelines
// and has no effect on the reasoning logic.
type Telemetry struct {
	// SessionID is a client-generated correlation identifier.
	SessionID string `json:"session_id" example:"sess-a1b2c3"`

	// TimestampUnix is the Unix epoch (seconds) at which the client created the request.
	TimestampUnix int64 `json:"timestamp_unix" example:"1713340800"`

	// DurationMs records how long the client spent on the assessment before requesting a plan.
	DurationMs float64 `json:"duration_ms,omitempty" example:"12345.6"`

	// ClientVersion identifies the frontend application version for compatibility tracking.
	ClientVersion string `json:"client_version,omitempty" example:"2.4.1"`
}

// GraphTuple is the domain representation of a single knowledge-graph triple
// in Subject-Relation-Object (SRO) form. The AxiomEngine models all
// curriculum prerequisite relationships as directed edges of this type.
//
// Example: {Subject: "Polymorphism", Relation: "depends_on", Object: "Inheritance"}
// denotes that mastering Polymorphism requires prior mastery of Inheritance.
type GraphTuple struct {
	// Subject is the source node of the directed edge.
	Subject string `json:"subject" example:"Polymorphism"`

	// Relation is the labeled edge type. Common values: "depends_on", "is_a".
	Relation string `json:"relation" example:"depends_on"`

	// Object is the target node of the directed edge.
	Object string `json:"object" example:"Inheritance"`
}

// PlanResponse is the top-level envelope returned by POST /api/v1/adaptive-plan.
// It contains the ordered list of study items produced by the reasoning pipeline
// together with a metadata block exposing internal pipeline telemetry.
type PlanResponse struct {
	// StudentID is echoed from the request for client-side correlation.
	StudentID string `json:"student_id" example:"student-42"`

	// CourseID is echoed from the request for client-side correlation.
	CourseID string `json:"course_id" example:"cs101"`

	// Items is the ordered sequence of study items, priority-sorted (1 = study first).
	Items []PlanItem `json:"items"`

	// Meta exposes internal pipeline metrics for observability dashboards.
	// Serialized under the "_meta" key to distinguish it from domain data.
	Meta PipelineMeta `json:"_meta"`
}

// PlanItem represents a single actionable study unit within an adaptive plan.
// Each item maps to a node in the knowledge graph and is enriched with
// VARK-appropriate learning resources by the LLM.
type PlanItem struct {
	// Topic is the knowledge-graph node name this item targets.
	Topic string `json:"topic" example:"Polymorphism"`

	// Priority determines the recommended study order. 1 = highest priority
	// (study first). Included prerequisites precede their dependent topics.
	Priority int `json:"priority" example:"1"`

	// PrerequisiteChain lists the ordered prerequisite path leading to this
	// topic, extracted from the knowledge graph via topological sort.
	PrerequisiteChain []string `json:"prerequisite_chain" example:"Variables,Objects,Classes,Inheritance"`

	// Explanation is a concise rationale generated by the LLM describing
	// why this topic is relevant to the student's failed assessment. It contains
	// at most 1000 runes, with Unicode control and format characters removed.
	Explanation string `maxLength:"1000" json:"explanation" example:"Polymorphism allows objects to be treated as instances of their parent class."`

	// Resources contains 0-3 learning resources whose type strictly matches
	// the student's VARK profile.
	Resources []Resource `json:"resources" validate:"max=3"`
}

// Resource describes a single learning asset recommended within a PlanItem.
// The ResourceType field is constrained by the student's VARK profile to
// ensure pedagogical alignment.
type Resource struct {
	// Title is a name of at most 200 runes, with Unicode control and format characters removed.
	Title string `maxLength:"200" json:"title" example:"Polymorphism in Java – Visual Guide"`

	// URL is an absolute HTTP(S) link without userinfo, at most 2048 characters.
	URL string `maxLength:"2048" json:"url" example:"https://example.com/polymorphism-visual"`

	// ResourceType is normalized to lowercase and restricted to these values per VARK:
	//   kinesthetic: "exercise", "lab", "coding-challenge"
	//   visual:      "video", "diagram", "infographic"
	//   auditory:    "podcast", "lecture", "audio-course"
	//   read_write:  "article", "textbook", "documentation"
	ResourceType string `json:"resource_type" example:"video"`
}

// PipelineMeta exposes internal performance and correctness metrics from
// a single execution of the reasoning pipeline. It is embedded in every
// PlanResponse under the "_meta" key for observability and SLA monitoring.
type PipelineMeta struct {
	// SubgraphTuples is the number of knowledge-graph triples extracted
	// by the BFS subgraph traversal for the given failed topics.
	SubgraphTuples int `json:"subgraph_tuples" example:"12"`

	// TopicsProcessed is the count of failed topics that were individually
	// sent to the LLM via the parallel fan-out stage.
	TopicsProcessed int `json:"topics_processed" example:"2"`

	// ItemsGenerated is the total number of study items returned across
	// all per-topic LLM calls before deduplication.
	ItemsGenerated int `json:"items_generated" example:"6"`

	// ItemsValidated is the count of study items remaining after the
	// graph validation stage retains requested topics and their prerequisites.
	ItemsValidated int `json:"items_after_validation" example:"5"`

	// ItemsDropped counts distinct items outside the requested prerequisite closure.
	ItemsDropped int `json:"items_dropped" example:"1"`

	// LLMLatencyMs is the wall-clock time (milliseconds) spent waiting
	// for all parallel LLM calls to complete.
	LLMLatencyMs float64 `json:"llm_latency_ms" example:"3240.5"`

	// TotalLatencyMs is the end-to-end pipeline duration (milliseconds)
	// from request receipt to response serialization.
	TotalLatencyMs float64 `json:"total_latency_ms" example:"3312.8"`
}

// VisualNode represents a single concept node in the Cognitive Shadow Graph
// visualization. CognitiveState drives frontend rendering (e.g., color-coding
// in a Cytoscape.js or D3.js force-directed layout).
type VisualNode struct {
	// ID is the unique identifier for this node, equal to the knowledge-graph node name.
	ID string `json:"id" example:"Polymorphism"`

	// Label is the human-readable display text for the node.
	Label string `json:"label" example:"Polymorphism"`

	// CognitiveState indicates the student's cognitive state for this concept.
	// Possible values:
	//   "failed"   -- the student explicitly failed this topic.
	//   "learning" -- this topic is a prerequisite of a failed topic.
	//   "mastered" -- no evidence of deficit; presumed mastered.
	CognitiveState string `json:"cognitive_state" example:"failed"`
}

// VisualEdge represents a directed relationship between two nodes in the
// Cognitive Shadow Graph. Source and Target correspond to VisualNode IDs.
type VisualEdge struct {
	// Source is the ID of the originating node (the dependent concept).
	Source string `json:"source" example:"Polymorphism"`

	// Target is the ID of the destination node (the prerequisite concept).
	Target string `json:"target" example:"Inheritance"`

	// Relation is the edge label (e.g., "depends_on", "is_a").
	Relation string `json:"relation" example:"depends_on"`
}

// CognitiveGraphResponse is the payload returned by the
// GET /api/v1/tutor/student/:student_id/cognitive-graph endpoint.
// It provides a filtered, frontend-ready graph topology compatible with
// Cytoscape.js and D3.js visualization libraries. Only nodes with at least
// one edge in the filtered subgraph are included (no orphan nodes).
type CognitiveGraphResponse struct {
	// Nodes contains the filtered concept nodes, each annotated
	// with the student's cognitive state.
	Nodes []VisualNode `json:"nodes"`

	// Edges contains directed relationships between nodes in the subgraph.
	Edges []VisualEdge `json:"edges"`
}

// ErrorResponse is the JSON envelope for HTTP errors.
type ErrorResponse struct {
	// Error is a machine-readable error code (e.g., "validation_error",
	// "rate_limit_exceeded", "service_unavailable").
	Error string `json:"error" example:"validation_error"`

	// Details provides a human-readable explanation of the error cause.
	// Omitted when empty.
	Details string `json:"details,omitempty" example:"failed_topics must contain at least one topic"`
}

// HealthResponse is the payload returned by GET /health.
type HealthResponse struct {
	// Status is always "ok" when the service is running.
	Status string `json:"status" example:"ok"`
}
