package service

import (
	"axiom-reasoning-svc/baml_client/types"
	"axiom-reasoning-svc/internal/domain"
	"axiom-reasoning-svc/internal/graph"
)

// mapBAMLItemToDomain converts a single BAML-generated StudyItem (from the
// baml_client/types package) into the domain-layer PlanItem representation.
// This mapping isolates the BAML codegen boundary from the HTTP response layer,
// translating field names (e.g., Url -> URL, Resource_type -> ResourceType) to
// idiomatic Go conventions.
func mapBAMLItemToDomain(item types.StudyItem) domain.PlanItem {
	resources := make([]domain.Resource, len(item.Resources))
	for i, r := range item.Resources {
		resources[i] = domain.Resource{
			Title:        r.Title,
			URL:          r.Url,
			ResourceType: r.Resource_type,
		}
	}
	return domain.PlanItem{
		Topic:             item.Topic,
		Priority:          int(item.Priority),
		PrerequisiteChain: item.Prerequisite_chain,
		Explanation:       item.Explanation,
		Resources:         resources,
	}
}

// mergeAndDeduplicate combines study items from multiple per-topic
// AdaptiveStudyPlans produced by the parallel BAML fan-out stage. It
// deduplicates items by topic name (first occurrence wins), maps each to
// the domain PlanItem type, and re-assigns sequential 1-based priorities
// to the merged result.
func mergeAndDeduplicate(plans []types.AdaptiveStudyPlan) []domain.PlanItem {
	seen := make(map[string]bool, 16)
	merged := make([]domain.PlanItem, 0, 16)

	for _, plan := range plans {
		for _, item := range plan.Items {
			if seen[item.Topic] {
				continue
			}
			seen[item.Topic] = true
			merged = append(merged, mapBAMLItemToDomain(item))
		}
	}

	// Re-number priorities sequentially (1-based)
	for i := range merged {
		merged[i].Priority = i + 1
	}
	return merged
}

// validateAgainstGraph is the hallucination-guard stage of the reasoning
// pipeline. It iterates over the merged study items and drops any item whose
// Topic field does not correspond to an actual node in the knowledge graph.
// This prevents fabricated topic names generated by the LLM from propagating
// to the client. Surviving items are re-numbered with sequential priorities.
// The dropped count is returned for observability logging.
func validateAgainstGraph(items []domain.PlanItem, g *graph.InMemoryGraph) (valid []domain.PlanItem, dropped int) {
	valid = make([]domain.PlanItem, 0, len(items))
	for _, item := range items {
		if g.NodeExists(item.Topic) {
			valid = append(valid, item)
		} else {
			dropped++
		}
	}
	// Re-number after filtering
	for i := range valid {
		valid[i].Priority = i + 1
	}
	return valid, dropped
}

// mapDomainTuplesToBAML converts a slice of domain.GraphTuple values into
// the BAML-generated types.GraphTuple representation required by the
// generated BAML client functions. This translation exists because the BAML
// codegen produces its own struct types distinct from the domain layer.
func mapDomainTuplesToBAML(tuples []domain.GraphTuple) []types.GraphTuple {
	out := make([]types.GraphTuple, len(tuples))
	for i, t := range tuples {
		out[i] = types.GraphTuple{
			Subject:  t.Subject,
			Relation: t.Relation,
			Object:   t.Object,
		}
	}
	return out
}
